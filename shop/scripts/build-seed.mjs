// Generates supabase/seed_products.sql from assets/js/products.js so the
// server-side price list always matches the storefront catalogue.
// Usage: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(new URL('../assets/js/products.js', import.meta.url), 'utf8');
const ctx = { window: {} };
vm.runInNewContext(src + '\n;globalThis.__P = PRODUCTS;', ctx);
const products = ctx.__P;

const q = s => `'${String(s ?? '').replace(/'/g, "''")}'`;
const rows = products.map(p =>
  `  (${q(p.id)}, ${q(p.name)}, ${q(p.brand)}, ${Number(p.price)}, true)`).join(',\n');

const sql = `-- Generated by scripts/build-seed.mjs. Re-run after changing assets/js/products.js.
insert into public.products (id, name, collection, price_aed, active) values
${rows}
on conflict (id) do update set
  name = excluded.name,
  collection = excluded.collection,
  price_aed = excluded.price_aed,
  active = excluded.active,
  updated_at = now();
`;
writeFileSync(new URL('../supabase/seed_products.sql', import.meta.url), sql);
console.log(`wrote ${products.length} products`);
